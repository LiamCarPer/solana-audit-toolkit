//! Automated markdown audit report generator (`sat audit`).
//!
//! Turns a full static analysis into a professional audit report:
//! a metadata header, an executive summary with severity and confidence
//! distributions, findings grouped by SARIF rule id, an optional
//! transaction-report correlation section, and a fixed scope/limitations
//! section that mirrors the honest-limitations model of
//! `docs/EXPLOIT_CORPUS.md`.
//!
//! [`render_markdown`] is pure and side-effect free (fully testable);
//! [`run`] wires it to [`crate::analyzer::collect`] and writes the report
//! to disk. The orchestrator wires the CLI — wiring this module is exactly:
//!
//! ```text
//! // crates/sat/src/lib.rs
//! pub mod audit;
//! // crates/sat/src/main.rs
//! mod audit;
//! ```

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::Path;

use anyhow::{Context, Result};

use crate::analyzer;
use crate::sarif;
use crate::types::{Confidence, Finding, Severity};
use crate::ui;

/// Fixed "Scope & Honest Limitations" section. Mirrors the documented
/// limitations of `docs/EXPLOIT_CORPUS.md` and is kept identical across
/// every generated report.
const LIMITATIONS_SECTION: &str = "## Scope & Honest Limitations

This report is generated by static analysis of the program source. Every
finding is a lead, not proof of exploitability: `sat` inspects declared
constraints and source patterns, never runtime behavior. The absence of a
finding is therefore not an assertion of security, and each finding
requires manual verification before being submitted to an audit or bounty
program.

The following classes are explicitly out of scope for this static backend,
mirroring the documented limitations of `docs/EXPLOIT_CORPUS.md`:

- **Semantic field-level invariants** — a field may be validated, but not
  for the right invariant (e.g. an unchecked identity field inside a
  manually validated account chain).
- **Oracle economics** — price-feed manipulation, TWAP/confidence-interval
  reasoning, and liquidation math are protocol-specific concerns outside
  per-instruction pattern analysis.
- **Cross-instruction atomicity** — multi-transaction flows, replay
  protection (e.g. consumed-VAA tracking), and closed-account revival
  across instructions.
- **Governance logic** — post-exploit governance consequences and
  multi-sig / upgrade orchestration.

Per-finding manual verification steps are included in the Findings section.
A finding becomes actionable only after a human confirms the flagged
pattern is reachable and exploitable on the deployed program.
";

/// Renders the full markdown audit report for a set of findings.
///
/// Pure function: no I/O, no randomness, no mutable global state (only the
/// wall-clock generated date via `chrono`). Output structure:
///
/// - `# Audit Report — <program>` header with a metadata block (generated
///   date `%Y-%m-%d`, program id when known, finding count, rule count).
/// - `## Executive Summary` with severity counts and confidence
///   distribution derived from [`Finding::confidence`].
/// - `## Findings` grouped by rule id ([`sarif::classify_finding_rule`]),
///   then by severity descending, each finding as a definition-list block.
/// - `## Transaction Report Correlation` only when `tx_report_path` is set.
/// - `## Scope & Honest Limitations` (fixed section).
pub fn render_markdown(
    findings: &[Finding],
    program_name: &str,
    program_id: Option<&str>,
    tx_report_path: Option<&str>,
) -> String {
    let mut md = String::new();

    render_header(&mut md, findings, program_name, program_id);
    render_executive_summary(&mut md, findings);
    render_findings_section(&mut md, findings);
    render_tx_report_section(&mut md, tx_report_path);
    md.push_str(LIMITATIONS_SECTION);
    md.push('\n');

    md
}

