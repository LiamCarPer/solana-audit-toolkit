/// Renders a **self-contained** HTML audit report (embedded CSS, no external
/// assets) from the same data as [`render_markdown`]. Suitable as a client
/// deliverable or an artifact upload.
pub fn render_html(
    findings: &[Finding],
    program_name: &str,
    program_id: Option<&str>,
    tx_report_path: Option<&str>,
) -> String {
    let mut h = String::new();
    h.push_str("<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n");
    h.push_str("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n");
    h.push_str(&format!("<title>Audit Report — {}</title>\n", escape_html(program_name)));
    h.push_str(&format!("<style>{HTML_STYLE}</style>\n</head>\n<body>\n<main>\n"));

    // Header + metadata.
    h.push_str(&format!("<header><h1>Audit Report — {}</h1>\n<div class=\"meta\">\n", escape_html(program_name)));
    if let Some(pid) = program_id {
        h.push_str(&format!("Program ID: <code>{}</code><br>\n", escape_html(pid)));
    }
    h.push_str(&format!(
        "Generated: {} &middot; Findings: {} &middot; Rules: {}\n</div></header>\n",
        chrono::Local::now().format("%Y-%m-%d"),
        findings.len(),
        distinct_rule_count(findings)
    ));

    // Executive summary.
    h.push_str(
        "<section><h2>Executive Summary</h2>\n<table><thead><tr><th>Severity</th><th>Count</th></tr></thead><tbody>\n",
    );
    for severity in [Severity::Critical, Severity::High, Severity::Medium, Severity::Low, Severity::Informational] {
        let count = findings.iter().filter(|f| f.severity == severity).count();
        h.push_str(&format!(
            "<tr><td><span class=\"badge {}\">{}</span></td><td>{}</td></tr>\n",
            severity.to_string().to_ascii_lowercase(),
            severity,
            count
        ));
    }
    h.push_str("</tbody></table>\n");
    h.push_str("<table><thead><tr><th>Confidence</th><th>Count</th></tr></thead><tbody>\n");
    for confidence in [Confidence::High, Confidence::Medium, Confidence::Low] {
        let count = findings.iter().filter(|f| f.confidence() == confidence).count();
        h.push_str(&format!("<tr><td>{confidence}</td><td>{count}</td></tr>\n"));
    }
    h.push_str("</tbody></table></section>\n");

    // Findings.
    h.push_str("<section><h2>Findings</h2>\n");
    if findings.is_empty() {
        h.push_str("<p>No findings were produced by static analysis. This is not an assertion of security — see Scope &amp; Honest Limitations below.</p>\n");
    } else {
        let mut by_rule: BTreeMap<String, Vec<&Finding>> = BTreeMap::new();
        for finding in findings {
            by_rule.entry(sarif::classify_finding_rule(finding)).or_default().push(finding);
        }
        for rule_findings in by_rule.values_mut() {
            rule_findings.sort_by_key(|f| std::cmp::Reverse(severity_rank(f.severity)));
            for finding in rule_findings {
                render_finding_html(&mut h, finding);
            }
        }
    }
    h.push_str("</section>\n");

    if let Some(path) = tx_report_path {
        h.push_str("<section><h2>Transaction Report Correlation</h2>\n<p>SAT011 correlation checks were performed against the on-chain transaction report at <code>");
        h.push_str(&escape_html(path));
        h.push_str("</code>. Correlation results are strong leads; each flagged account must still be confirmed against the program source and a live replay before submission.</p></section>\n");
    }

    h.push_str(LIMITATIONS_HTML);
    h.push_str("\n</main>\n</body>\n</html>\n");
    h
}

fn render_finding_html(h: &mut String, finding: &Finding) {
    let rule = sarif::classify_finding_rule(finding);
    let sev = finding.severity.to_string().to_ascii_lowercase();

    h.push_str(&format!("<article class=\"finding {sev}\">\n"));
    h.push_str(&format!(
        "<h3><span class=\"badge {sev}\">{}</span> {} — {}</h3>\n",
        finding.severity,
        escape_html(&finding.id),
        escape_html(&finding.title)
    ));
    h.push_str(&format!(
        "<div class=\"meta\"><span class=\"rule\">{}</span> &middot; Confidence: {}</div>\n",
        escape_html(&rule),
        finding.confidence()
    ));
    if let Some(location) = &finding.location {
        h.push_str(&format!("<div class=\"loc\">{}</div>\n", escape_html(location)));
    }
    let affected = finding.affected_accounts();
    if !affected.is_empty() {
        h.push_str(&format!("<p><strong>Affected accounts:</strong> {}</p>\n", escape_html(&affected.join(", "))));
    }
    h.push_str(&format!("<p><strong>Description:</strong></p>\n<pre>{}</pre>\n", escape_html(&finding.description)));
    if let Some(suggestion) = &finding.suggestion {
        h.push_str(&format!("<p><strong>Suggestion:</strong></p>\n<pre>{}</pre>\n", escape_html(suggestion)));
    }
    let steps = finding.manual_verification_steps();
    if !steps.is_empty() {
        h.push_str("<p><strong>Manual verification:</strong></p>\n<ol>\n");
        for step in &steps {
            h.push_str(&format!("<li>{}</li>\n", escape_html(step)));
        }
        h.push_str("</ol>\n");
    }
    h.push_str("</article>\n");
}

/// Minimal HTML escaping for untrusted finding text.
fn escape_html(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            _ => out.push(c),
        }
    }
    out
}

/// Runs the full analysis pipeline and writes the audit report (`md` or `html`).
///
/// Program identity resolution order: Anchor IDL name (with `metadata.address`
/// as the program id), else the native program's `program_id`, else the source
/// path stem. The report is written to `out_path` or `audit-report.<ext>` in the
/// current working directory.
pub fn run(src_path: Option<&str>, out_path: Option<&str>, tx_report: Option<&str>, format: &str) -> Result<()> {
    let output = analyzer::collect(src_path, tx_report, None)?;

    if output.parsed_files.is_empty() {
        anyhow::bail!(
            "No Rust source files could be parsed under {:?}. Pass an existing program directory or file.",
            src_path.unwrap_or("<default source search>")
        );
    }

    let (program_name, program_id) = resolve_program_identity(&output, src_path);

    let html = format.eq_ignore_ascii_case("html");
    let report = if html {
        render_html(&output.findings, &program_name, program_id.as_deref(), tx_report)
    } else {
        render_markdown(&output.findings, &program_name, program_id.as_deref(), tx_report)
    };

    let default_name = if html { "audit-report.html" } else { "audit-report.md" };
    let report_path = out_path.unwrap_or(default_name);
    fs::write(report_path, report).with_context(|| format!("Failed to write audit report to {report_path}"))?;

    ui::print_success(&format!(
        "Audit report written to {report_path} ({program_name}, {} finding(s)).",
        output.findings.len()
    ));

    Ok(())
}

// ── Report sections ───────────────────────────────────────────────────────────

fn render_header(md: &mut String, findings: &[Finding], program_name: &str, program_id: Option<&str>) {
    md.push_str(&format!("# Audit Report \u{2014} {program_name}\n\n"));
    md.push_str("| Field | Value |\n| --- | --- |\n");
    md.push_str(&format!("| Program | `{program_name}` |\n"));
    if let Some(pid) = program_id {
        md.push_str(&format!("| Program ID | `{pid}` |\n"));
    }
    let generated = chrono::Local::now().format("%Y-%m-%d");
    md.push_str(&format!("| Generated | {generated} |\n"));
    md.push_str(&format!("| Findings | {} |\n", findings.len()));
    md.push_str(&format!("| Rules | {} |\n\n", distinct_rule_count(findings)));
}

fn render_executive_summary(md: &mut String, findings: &[Finding]) {
    md.push_str("## Executive Summary\n\n");

    md.push_str("| Severity | Count |\n| --- | --- |\n");
    for severity in [Severity::Critical, Severity::High, Severity::Medium, Severity::Low, Severity::Informational] {
        let count = findings.iter().filter(|f| f.severity == severity).count();
        md.push_str(&format!("| {severity} | {count} |\n"));
    }

    md.push_str("\n| Confidence | Count |\n| --- | --- |\n");
    for confidence in [Confidence::High, Confidence::Medium, Confidence::Low] {
        let count = findings.iter().filter(|f| f.confidence() == confidence).count();
        md.push_str(&format!("| {confidence} | {count} |\n"));
    }

    md.push('\n');
}

fn render_findings_section(md: &mut String, findings: &[Finding]) {
    md.push_str("## Findings\n\n");

    if findings.is_empty() {
        md.push_str(
            "No findings were produced by static analysis. This is not an assertion of security \
                     — see the Scope & Honest Limitations section below.\n\n",
        );
        return;
    }

    // Group by rule id (sorted), then severity descending, preserving the
    // original order within a severity bucket.
    let mut by_rule: BTreeMap<String, Vec<&Finding>> = BTreeMap::new();
    for finding in findings {
        by_rule.entry(sarif::classify_finding_rule(finding)).or_default().push(finding);
    }
    for rule_findings in by_rule.values_mut() {
        rule_findings.sort_by_key(|f| std::cmp::Reverse(severity_rank(f.severity)));
        for finding in rule_findings {
            render_finding(md, finding);
        }
    }
}

fn render_finding(md: &mut String, finding: &Finding) {
    let rule = sarif::classify_finding_rule(finding);

    md.push_str(&format!("### {} \u{2014} {}\n\n", finding.id, finding.title));
    md.push_str(&format!("**Severity:** {}\n", finding.severity));
    md.push_str(&format!("**Confidence:** {}\n", finding.confidence()));
    md.push_str(&format!("**Rule:** {rule}\n"));

    if let Some(location) = &finding.location {
        md.push_str(&format!("\n**Location:** `{location}`\n"));
    }

    let affected = finding.affected_accounts();
    if !affected.is_empty() {
        md.push_str(&format!("\n**Affected accounts:** {}\n", affected.join(", ")));
    }

    md.push_str("\n**Description:**\n\n");
    md.push_str(&finding.description);
    md.push('\n');

    if let Some(suggestion) = &finding.suggestion {
        md.push_str("\n**Suggestion:**\n\n");
        md.push_str(suggestion);
        md.push('\n');
    }

    let steps = finding.manual_verification_steps();
    if !steps.is_empty() {
        md.push_str("\n**Manual verification:**\n\n");
        for (index, step) in steps.iter().enumerate() {
            md.push_str(&format!("{}. {step}\n", index + 1));
        }
    }

    md.push('\n');
}

fn render_tx_report_section(md: &mut String, tx_report_path: Option<&str>) {
    if let Some(path) = tx_report_path {
        md.push_str("## Transaction Report Correlation\n\n");
        md.push_str(&format!(
            "The findings in this report include **SAT011** correlation checks performed against the \
             on-chain transaction report at `{path}`. These findings compare declared account \
             constraints with observed runtime behavior from the transaction report. Correlation \
             results are strong leads, but each flagged account must still be confirmed against the \
             program source and a live replay before submission.\n\n"
        ));
    }
}

// ── Helpers ───────────────────────────────────────────────────────────────────

/// Distinct rule id count across findings, using the same rule classifier
/// the SARIF exporter and the per-finding blocks use.
fn distinct_rule_count(findings: &[Finding]) -> usize {
    let mut rules = BTreeSet::new();
    for finding in findings {
        rules.insert(sarif::classify_finding_rule(finding));
    }
    rules.len()
}

/// Descending severity order: Critical (5) through Informational (1).
fn severity_rank(severity: Severity) -> u8 {
    match severity {
        Severity::Critical => 5,
        Severity::High => 4,
        Severity::Medium => 3,
        Severity::Low => 2,
        Severity::Informational => 1,
    }
}

/// Resolves the report's program identity: Anchor IDL name (with
/// `metadata.address` as program id), else the native program id, else the
/// source path stem (or `program` when none is derivable).
fn resolve_program_identity(output: &analyzer::AnalysisOutput, src_path: Option<&str>) -> (String, Option<String>) {
    if let Some(idl) = &output.ctx.idl {
        let program_id = idl.metadata.as_ref().and_then(|meta| meta.address.clone());
        return (idl.name.clone(), program_id);
    }

    if let Some(program_id) = output.native_program.as_ref().and_then(|program| program.program_id.clone()) {
        return (program_id.clone(), Some(program_id));
    }

    let stem = src_path
        .map(Path::new)
        .and_then(|path| path.file_stem())
        .and_then(|stem| stem.to_str())
        .filter(|stem| !stem.is_empty())
        .unwrap_or("program");
    (stem.to_string(), None)
}
